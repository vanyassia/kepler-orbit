/**
 * Липкий выбор места подписи у движущейся точки (концы трассы на карте).
 *
 * Места пробуются по порядку: 0 — главное (справа), дальше — запасные. Если выбирать каждый кадр
 * просто первое свободное, то при быстром времени главное место то занято соседней меткой, то свободно,
 * и подпись мечется между двумя местами — на глаз она двоится. Поэтому подпись остаётся на прежнем
 * месте, пока оно свободно, а на главное возвращается, только когда оно свободно уже несколько кадров подряд.
 */
export interface SpotMemory {
  /** Где подпись стояла последний раз. */
  spot: number;
  /** Сколько кадров подряд главное место свободно. */
  homeFree: number;
}

/** Сколько кадров подряд главное место должно быть свободно, чтобы подпись вернулась на него (≈ полсекунды). */
export const SETTLE_FRAMES = 30;

/**
 * Место для подписи в этом кадре (−1 — свободного места нет, подпись не рисуется)
 * и память для следующего кадра.
 */
export function chooseSpot(mem: SpotMemory | undefined, free: boolean[], settle = SETTLE_FRAMES): { spot: number; mem: SpotMemory } {
  // Первый кадр: памяти нет — главное место считается давно свободным
  const homeFree = free[0] ? (mem ? mem.homeFree : settle) + 1 : 0;
  const prev = mem?.spot ?? 0;
  const spot = prev > 0 && free[prev] && homeFree <= settle ? prev : free.indexOf(true);
  return { spot, mem: { spot: spot < 0 ? prev : spot, homeFree } };
}
