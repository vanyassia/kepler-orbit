/**
 * Физические постоянные модели.
 *
 * Модель (см. docs/formulas.md, раздел «Допущения»):
 *  - Земля — однородный шар (центральное ньютоновское поле, задача двух тел);
 *  - возмущения (сжатие Земли, атмосфера, Луна, Солнце, давление света) не учитываются.
 *
 * Единицы внутри модуля physics: километры, секунды, радианы.
 */

/** Гравитационный параметр Земли μ, км³/с² (по листку «Трасса спутника»). */
export const MU = 398602;

/**
 * Радиус Земли R_З, км. Для шарообразной Земли берём средний радиус 6371 км:
 * он даёт наименьшую среднюю ошибку высоты по сравнению с эллипсоидом.
 */
export const R_EARTH = 6371.0;

/** Звёздные сутки — один оборот Земли относительно звёзд: 86 164 с = 1436,0667 мин. */
export const SIDEREAL_DAY_MIN = 1436.0667;

/** Скорость вращения Земли ω_З = 360° / 1436,0667 мин = 0,250684 °/мин. */
export const OMEGA_EARTH_DEG_PER_MIN = 360 / SIDEREAL_DAY_MIN;

/** То же в рад/с. */
export const OMEGA_EARTH = (2 * Math.PI) / (SIDEREAL_DAY_MIN * 60);

/** Число секунд в средних солнечных сутках. */
export const SECONDS_PER_DAY = 86400;

/** Юлианская дата эпохи J2000.0 (2000-01-01 12:00 TT). */
export const JD_J2000 = 2451545.0;

/** Юлианская дата начала отсчёта Unix-времени (1970-01-01 00:00 UTC). */
export const JD_UNIX_EPOCH = 2440587.5;

export const TWO_PI = 2 * Math.PI;
export const DEG = Math.PI / 180;
export const RAD = 180 / Math.PI;
