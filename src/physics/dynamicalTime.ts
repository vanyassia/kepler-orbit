/**
 * Даты изменения TAI − UTC после введения високосных секунд (таблица NAIF).
 * TDB здесь принимается равным TT: периодическая разница меньше 2 мс.
 */
const LEAP_DATES = [
  [1972, 6], [1973, 0], [1974, 0], [1975, 0], [1976, 0], [1977, 0], [1978, 0], [1979, 0], [1980, 0],
  [1981, 6], [1982, 6], [1983, 6], [1985, 6], [1988, 0], [1990, 0], [1991, 0], [1992, 6], [1993, 6],
  [1994, 6], [1996, 0], [1997, 6], [1999, 0], [2006, 0], [2009, 0], [2012, 6], [2015, 6], [2017, 0],
].map(([year, month]) => Date.UTC(year, month, 1));

export function tdbMinusUtc(t: number): number {
  for (let i = LEAP_DATES.length - 1; i >= 0; i--) if (t >= LEAP_DATES[i]) return 43.184 + i;
  return 42.184;
}
